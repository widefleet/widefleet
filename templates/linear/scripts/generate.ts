// Writes src/tools.ts, one method per tool of Linear's MCP server.
//
//   LINEAR_TOKEN=... pnpm generate
//
// The token needs the read and write scopes, so the list includes Linear's
// writing tools. A Linear API key works too. Review the diff before committing:
// it shows changed tools and which of them ask the user before running.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { listTools, needsApproval, rpcRequest, rpcResult, tool } from "../src/linear.ts";
import { comment, jsonSchema, methodName, optionalInput, schemaType } from "./schema-types.ts";

const token = z
  .string({ error: "Set LINEAR_TOKEN to a Linear token with the read and write scopes" })
  .min(1)
  .parse(process.env["LINEAR_TOKEN"]);

const tools: z.infer<typeof tool>[] = [];

let cursor: string | undefined;

do {
  const page = listTools(cursor);
  const response = await fetch(rpcRequest(page, token));

  if (!response.ok) throw new Error(`Linear answered HTTP ${response.status}`);
  const result = await rpcResult(page, response);
  tools.push(...result.tools);
  cursor = result.nextCursor;
} while (cursor);

// Names the generated class, Widefleet or Workers RPC already use.
const reserved = new Set([
  "connectionStatus",
  "withInput",
  "constructor",
  "fetch",
  "connect",
  "scheduled",
  "queue",
  "alarm",
  "then",
  "catch",
  "finally",
  "toString",
  "valueOf",
  "dup",
]);

const methods = new Set<string>();

const method = (entry: z.infer<typeof tool>) => {
  const name = methodName(entry.name);

  if (reserved.has(name) || methods.has(name))
    throw new Error(`Tool ${entry.name} becomes method ${name}, which is taken`);
  methods.add(name);

  const parsed = jsonSchema.safeParse(entry.inputSchema);

  if (!parsed.success)
    throw new Error(`Tool ${entry.name} has an unsupported input schema: ${parsed.error.message}`);
  const schema = parsed.data;
  const title = entry.annotations?.title ?? entry.title ?? entry.name;
  const approval = needsApproval(entry.annotations);

  const behavior = approval
    ? "Asks the user before running: Linear marks this tool as able to delete or overwrite data."
    : entry.annotations?.readOnlyHint
      ? "Only reads."
      : "Writes without asking: Linear marks this tool as not destructive.";

  const parameter = `input: ${schemaType(schema, "  ")}${optionalInput(schema) ? " = {}" : ""}`;

  return `${comment(`${entry.description ?? title}\n\n${behavior}`, "  ")}  async ${name}(${parameter}) {
    return runTool(this.env, this.ctx.props, ${JSON.stringify(entry.name)}, input, {
      title: ${JSON.stringify(title)},
      approval: ${approval},
      // Linear's schema as published, which runtime validation uses.
      schema: ${JSON.stringify(entry.inputSchema)},
    });
  }
`;
};

const source = `// Generated by \`pnpm generate\` from the tool list of Linear's MCP server.
// Do not edit; run the script again to pick up Linear's changes.
import { WorkerEntrypoint } from "cloudflare:workers";
import type { Environment } from "./context.ts";
import { type Json, type LinearProperties, runTool } from "./tool-call.ts";

/** Every tool of Linear's MCP server, as a method. */
export class LinearTools extends WorkerEntrypoint<Environment, LinearProperties> {
${tools
  .toSorted((a, b) => a.name.localeCompare(b.name))
  .map(method)
  .join("\n")}}
`;

writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "../src/tools.ts"), source);

console.log(`Wrote ${tools.length} tools to src/tools.ts`);
